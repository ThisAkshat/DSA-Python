# This program stores student details and prints them

student_name = "Rahul"
student_age = 19
student_marks = 85.5

print("Student Name:", student_name)
print("Student Age:", student_age)
print("Student Marks:", student_marks)


# Code Explanation
# Line: student_name = "Rahul"

# What it does: Creates a variable called student_name and stores the text "Rahul" in it.
# Why it is needed: We need a way to remember the student's name.
# If removed: Python will give an error later when we try to print student_name, because it does not exist.

# Line: student_age = 19

# What it does: Creates a variable called student_age and stores the number 19.
# Why it is needed: To remember the student's age.
# If removed: The print(student_age) line will fail with an error.

# Line: student_marks = 85.5

# What it does: Creates a variable called student_marks and stores a decimal number 85.5.
# Why it is needed: To remember the student's marks.
# If removed: The marks print line will fail.

# Line: print("Student Name:", student_name)

# What it does: Shows the text Student Name: followed by the value inside student_name.
# Why it is needed: To display the result on the screen.
# If removed: We will not see the student's name in the output.
